-- 1. Users Table (Authentication, BCrypt password hash, Role, Lockout tracking)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(128) NOT NULL,
    role VARCHAR(32) NOT NULL, -- ROLE_SIGNER, ROLE_VERIFIER, ROLE_ADMIN
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    failed_logins INT DEFAULT 0,
    locked_until TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);

-- 2. Key Pairs Table (Public metadata & PEM only - NEVER stores private key bytes)
CREATE TABLE IF NOT EXISTS public.key_pairs (
    key_id VARCHAR(64) PRIMARY KEY, -- SHA-256 SPKI fingerprint
    owner_id BIGINT NOT NULL,
    label VARCHAR(128) NOT NULL,
    public_pem TEXT NOT NULL,
    key_file_path VARCHAR(512) NOT NULL,
    status VARCHAR(32) NOT NULL, -- ACTIVE, RETIRED, REVOKED
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_key_pairs_owner FOREIGN KEY (owner_id) REFERENCES public.users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_key_pairs_owner ON public.key_pairs(owner_id);
CREATE INDEX IF NOT EXISTS idx_key_pairs_status ON public.key_pairs(status);

-- 3. Trusted Signers Table (Trust store, pinned fingerprints, revocation status)
CREATE TABLE IF NOT EXISTS public.trusted_signers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    label VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL, -- TRUSTED, REVOKED, RETIRED, UNTRUSTED
    added_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ,
    note VARCHAR(256),
    CONSTRAINT fk_trusted_signers_owner FOREIGN KEY (owner_id) REFERENCES public.users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_trusted_signers_owner ON public.trusted_signers(owner_id);
CREATE INDEX IF NOT EXISTS idx_trusted_signers_fingerprint ON public.trusted_signers(fingerprint);

-- 4. Verification Records Table (Verification history, audit of verification outcomes)
CREATE TABLE IF NOT EXISTS public.verification_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    doc_name VARCHAR(255) NOT NULL,
    doc_sha256 VARCHAR(64) NOT NULL,
    key_id VARCHAR(64),
    result_code VARCHAR(32) NOT NULL,
    trust_status VARCHAR(32),
    signed_at TIMESTAMPTZ,
    verified_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    nonce VARCHAR(64),
    CONSTRAINT fk_verif_records_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_verif_records_user ON public.verification_records(user_id);
CREATE INDEX IF NOT EXISTS idx_verif_records_verified_at ON public.verification_records(verified_at DESC);

-- 5. Tamper-Evident Chained Audit Log Table (Cryptographically chained SHA-256 sequence)
CREATE TABLE IF NOT EXISTS public.audit_log (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_id BIGINT,
    action VARCHAR(64) NOT NULL,
    detail VARCHAR(1024),
    prev_hash VARCHAR(64) NOT NULL,
    entry_hash VARCHAR(64) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_log_seq ON public.audit_log(seq);
CREATE INDEX IF NOT EXISTS idx_audit_log_timestamp ON public.audit_log(timestamp DESC);

-- Enable Row Level Security (RLS) on Supabase (Optional best-practice for PostgreSQL)
-- When connecting directly via JDBC postgres user, full access is preserved.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.key_pairs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trusted_signers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.verification_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_log ENABLE ROW LEVEL SECURITY;

-- Default service access policy
CREATE POLICY "Allow service direct access" ON public.users FOR ALL USING (true);
CREATE POLICY "Allow service direct access" ON public.key_pairs FOR ALL USING (true);
CREATE POLICY "Allow service direct access" ON public.trusted_signers FOR ALL USING (true);
CREATE POLICY "Allow service direct access" ON public.verification_records FOR ALL USING (true);
CREATE POLICY "Allow service direct access" ON public.audit_log FOR ALL USING (true);
